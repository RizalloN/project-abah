    /**
     * Look up official RM target by PN or Name.
     *
     * @return array{target_deb: int, target_os: float, jg: string}|null
     */
    public static function findRm(string $identifier): ?array
    {
        $raw = trim($identifier);
        if ($raw === '') {
            return null;
        }

        // Split "00369254 - MOCHAMMAD SAMSUL ARIFIN"
        $parts = str_contains($raw, '-') ? explode('-', $raw, 2) : [$raw];
        $partPn = trim($parts[0]);
        $partName = isset($parts[1]) ? trim($parts[1]) : '';

        // Check by PN (numeric)
        if (preg_match('/\b(\d{5,8})\b/', $partPn, $matches)) {
            $pn = str_pad(ltrim($matches[1], '0'), 8, '0', STR_PAD_LEFT);
            if (isset(self::ROSTER[$pn]) && self::ROSTER[$pn]['target_os'] > 0) {
                $r = self::ROSTER[$pn];
                return [
                    'pn' => $r['pn'],
                    'nama' => $r['nama'],
                    'target_deb' => $r['target_deb'],
                    'target_os' => $r['target_os'],
                    'jg' => $r['jg'],
                    'record' => $r,
                ];
            }
        }

        // Check also in full raw string for PN
        if (preg_match('/\b(\d{5,8})\b/', $raw, $matches)) {
            $pn = str_pad(ltrim($matches[1], '0'), 8, '0', STR_PAD_LEFT);
            if (isset(self::ROSTER[$pn]) && self::ROSTER[$pn]['target_os'] > 0) {
                $r = self::ROSTER[$pn];
                return [
                    'pn' => $r['pn'],
                    'nama' => $r['nama'],
                    'target_deb' => $r['target_deb'],
                    'target_os' => $r['target_os'],
                    'jg' => $r['jg'],
                    'record' => $r,
                ];
            }
        }

        // Check by normalized Name (test partName first if available, then raw)
        $candidates = array_filter([$partName, $raw]);
        foreach ($candidates as $cand) {
            $nameClean = preg_replace('/[^A-Z0-9]/', '', strtoupper($cand)) ?? '';
            $nameClean = preg_replace('/^(RM|RMBISNISKONSUMER)+/', '', $nameClean);
            if (strlen($nameClean) >= 3) {
                // First pass: exact match
                foreach (self::ROSTER as $r) {
                    if (!empty($r['name_key']) && $r['name_key'] === $nameClean && $r['target_os'] > 0) {
                        return [
                            'pn' => $r['pn'],
                            'nama' => $r['nama'],
                            'target_deb' => $r['target_deb'],
                            'target_os' => $r['target_os'],
                            'jg' => $r['jg'],
                            'record' => $r,
                        ];
                    }
                }
                // Second pass: substring match for names with middle initials or full names
                if (strlen($nameClean) >= 5) {
                    foreach (self::ROSTER as $r) {
                        if (!empty($r['name_key']) && strlen($r['name_key']) >= 5 && $r['target_os'] > 0) {
                            if (str_contains($r['name_key'], $nameClean) || str_contains($nameClean, $r['name_key'])) {
                                return [
                                    'pn' => $r['pn'],
                                    'nama' => $r['nama'],
                                    'target_deb' => $r['target_deb'],
                                    'target_os' => $r['target_os'],
                                    'jg' => $r['jg'],
                                    'record' => $r,
                                ];
                            }
                        }
                    }
                }
            }
        }

        return null;
    }

    /**
     * Resolve target (Deb & OS) from identifier or JG with fallback.
     *
     * @return array{target_deb: int, target_os: float}
     */
    public static function resolveTarget(string $identifier, ?string $jg = null): array
    {
        $found = self::findRm($identifier);
        if ($found !== null && $found['target_os'] > 0) {
            return [
                'target_deb' => $found['target_deb'],
                'target_os' => $found['target_os'],
            ];
        }

        if ($jg !== null) {
            $normalizedJg = strtoupper(trim($jg));
            if (isset(self::DEFAULT_TARGET_BY_JG[$normalizedJg])) {
                return self::DEFAULT_TARGET_BY_JG[$normalizedJg];
            }
        }

        // Default to standard JG05 if unknown
        return self::DEFAULT_TARGET_BY_JG['JG05'];
    }

    /**
     * Calculate Consumer RM Quadrant according to official Kanwil formula.
     *
     * >= 105.0% => Kuadran 1
     * >= 100.0% => Kuadran 2
     * >= 50.0%  => Kuadran 3
     * < 50.0%   => Kuadran 4
     */
    public static function calculateQuadrant(mixed $realisationOs, float $targetOs): ?int
    {
        if ($targetOs <= 0.0) {
            return null;
        }

        $realisation = is_numeric($realisationOs) ? (float) $realisationOs : null;
        if ($realisation === null) {
            return null;
        }

        $pct = ($realisation / $targetOs) * 100;

        return match (true) {
            $pct >= 105.0 => 1,
            $pct >= 100.0 => 2,
            $pct >= 50.0 => 3,
            default => 4,
        };
    }
