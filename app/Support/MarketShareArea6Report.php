    private static function parseRows(string $block): array
    {
        return collect(preg_split('/\R/', trim($block)))
            ->filter()
            ->map(function (string $line): array {
                $parts = explode('|', $line);

                return [
                    'branch' => array_shift($parts),
                    'values' => $parts,
                    'total' => str_starts_with($line, 'Area 6|'),
                ];
            })
            ->values()
            ->all();
    }
